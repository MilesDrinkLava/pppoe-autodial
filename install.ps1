# install.ps1 - graphical setup wizard for pppoe-autodial
# Unattended: .\install.ps1 -ConnName <name> -User <account> -Pass <password> [-Reconnect]
# NOTE: keep this file saved as UTF-8 WITH BOM (contains Chinese UI text).
param(
    [string]$ConnName,
    [string]$User,
    [string]$Pass,
    [switch]$Reconnect,
    [int]$ReconnectSeconds = 0
)

$ErrorActionPreference = 'Stop'
$scriptRoot = $PSScriptRoot
$App = 'pppoe-autodial 安装程序'
$Unattended = [bool]($ConnName -and $User -and $Pass)
$reconnectSeconds = 15
if ($ReconnectSeconds -ge 10) { $reconnectSeconds = $ReconnectSeconds }

function Show-Info([string]$Text) {
    [void][System.Windows.Forms.MessageBox]::Show($Text, $App, [System.Windows.Forms.MessageBoxButtons]::OK, [System.Windows.Forms.MessageBoxIcon]::Information)
}
function Show-Err([string]$Text) {
    [void][System.Windows.Forms.MessageBox]::Show($Text, $App, [System.Windows.Forms.MessageBoxButtons]::OK, [System.Windows.Forms.MessageBoxIcon]::Error)
}
function Ask-YesNo([string]$Text, [bool]$DefaultNo = $true) {
    $def = if ($DefaultNo) { [System.Windows.Forms.MessageBoxDefaultButton]::Button2 } else { [System.Windows.Forms.MessageBoxDefaultButton]::Button1 }
    $r = [System.Windows.Forms.MessageBox]::Show($Text, $App, [System.Windows.Forms.MessageBoxButtons]::YesNo, [System.Windows.Forms.MessageBoxIcon]::Question, $def)
    return ($r -eq [System.Windows.Forms.DialogResult]::Yes)
}
function Ask-Text([string]$Prompt, [string]$Default = '') {
    return [Microsoft.VisualBasic.Interaction]::InputBox($Prompt, $App, $Default)
}
function Get-PppoeConnections {
    $names = @()
    $pbks = @(
        (Join-Path $env:APPDATA 'Microsoft\Network\Connections\Pbk\rasphone.pbk'),
        (Join-Path $env:ProgramData 'Microsoft\Network\Connections\Pbk\rasphone.pbk')
    )
    foreach ($pbk in $pbks) {
        if (-not (Test-Path $pbk)) { continue }
        $cur = $null; $isPppoe = $false
        foreach ($line in (Get-Content $pbk)) {
            if ($line -match '^\[(.+)\]\s*$') {
                if ($cur -and $isPppoe) { $names += $cur }
                $cur = $Matches[1]; $isPppoe = $false
            }
            elseif ($line -match '^device=(wan miniport \(pppoe\)|pppoe)') { $isPppoe = $true }
        }
        if ($cur -and $isPppoe) { $names += $cur }
    }
    return @($names | Select-Object -Unique)
}

try {
    Add-Type -AssemblyName System.Windows.Forms
    Add-Type -AssemblyName Microsoft.VisualBasic

    $conns = @(Get-PppoeConnections)

    if ($Unattended) {
        if ($conns -notcontains $ConnName) {
            Write-Host "ERROR: PPPoE connection '$ConnName' not found. Found: $($conns -join ', ')"
            exit 2
        }
    }
    else {
        if ($conns.Count -eq 0) {
            Show-Err "未检测到 PPPoE 宽带连接。`n`n请先创建宽带连接：`n控制面板 → 网络和共享中心 → 设置新的连接或网络 → 连接到 Internet → 宽带(PPPoE)`n`n创建后重新运行本安装程序。"
            exit 1
        }
        if ($conns.Count -eq 1) {
            $pick = $conns[0]
            if (-not (Ask-YesNo "检测到拨号连接【$pick】。`n`n将把它配置为开机自动拨号，是否继续？" $false)) { exit 0 }
            $ConnName = $pick
        }
        else {
            $list = ''
            for ($i = 0; $i -lt $conns.Count; $i++) { $list += ("{0}. {1}`n" -f ($i + 1), $conns[$i]) }
            $sel = Ask-Text "检测到多个拨号连接，请输入要配置的连接编号：`n`n$list"
            $idx = 0
            if (-not [int]::TryParse($sel, [ref]$idx) -or $idx -lt 1 -or $idx -gt $conns.Count) { Show-Err '输入无效，安装已取消。'; exit 1 }
            $ConnName = $conns[$idx - 1]
        }

        $account = Ask-Text '请输入宽带账号：'
        if ([string]::IsNullOrWhiteSpace($account)) { Show-Err '账号为空，安装已取消。'; exit 1 }
        $User = $account.Trim()

        $secret = Ask-Text '请输入宽带密码：'
        if ([string]::IsNullOrEmpty($secret)) { Show-Err '密码为空，安装已取消。'; exit 1 }
        $Pass = $secret

        $Reconnect = Ask-YesNo "是否启用「掉线自动重连」？`n`n启用：网络掉线后自动重拨（无后台常驻进程，不影响性能）。`n不启用：仅开机时自动拨号。`n`n（默认不启用）" $true
        if ($Reconnect) {
            $secInput = Ask-Text "请设置掉线检测间隔（秒）：`n`n· 推荐 15：掉线后 15 秒内自动恢复`n· 最小 10，最大不限`n`n间隔越短恢复越快，资源占用略增（15 秒时约占用 0.2% CPU，可忽略）。" '15'
            $n = 0
            if ([int]::TryParse($secInput, [ref]$n) -and $n -ge 10) {
                $reconnectSeconds = $n
            }
            else {
                $reconnectSeconds = 15
                Show-Info '输入无效（需为不小于 10 的整数），已使用推荐值 15 秒。'
            }
        }
    }

    # ---- deploy ----
    Write-Host "Deploying for connection '$ConnName' ..."
    $configContent = @(
        "# Generated by install.ps1 on $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')",
        "`$connName = '$ConnName'",
        "`$userName = '$User'",
        "# Reconnect check interval in seconds (applies when reconnect is enabled)",
        "`$reconnectSeconds = $reconnectSeconds",
        ''
    ) -join "`r`n"
    [IO.File]::WriteAllText((Join-Path $scriptRoot 'config.ps1'), $configContent, [Text.UTF8Encoding]::new($true))

    $sec = ConvertTo-SecureString $Pass -AsPlainText -Force
    Set-Content -Path (Join-Path $scriptRoot 'cred.dat') -Value (ConvertFrom-SecureString $sec) -Encoding ASCII

    $regArgs = @('-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', (Join-Path $scriptRoot 'register-task.ps1'))
    if ($Reconnect) { $regArgs += '-Reconnect' }
    $regOut = & powershell.exe @regArgs
    if ($LASTEXITCODE -ne 0) { throw "任务注册失败 (exit $LASTEXITCODE):`n$regOut" }
    $taskName = "AutoDial-$ConnName"
    Write-Host "Task '$taskName' registered. reconnect=$([bool]$Reconnect)"

    if ($Unattended) {
        Write-Host 'OK: deployed.'
        exit 0
    }

    # ---- optional live disconnect test ----
    $doTest = Ask-YesNo "部署完成！`n`n是否立即进行一次断线重拨测试，验证账号密码是否正确？`n（会断开当前网络约 10 秒）" $true
    if ($doTest) {
        Write-Host 'Running live disconnect test ...'
        rasdial $ConnName /disconnect | Out-Null
        Start-Sleep -Seconds 2
        Start-ScheduledTask -TaskName $taskName
        $ok = $false
        for ($i = 1; $i -le 12; $i++) {
            Start-Sleep -Seconds 2
            $iface = Get-NetIPInterface -InterfaceAlias $ConnName -AddressFamily IPv4 -ErrorAction SilentlyContinue
            if ($iface -and $iface.ConnectionState -eq 'Connected') { $ok = $true; break }
        }
        if ($ok) {
            $guard = if ($Reconnect) { "`n`n掉线自动重连已启用：断线后 $reconnectSeconds 秒内自动恢复。" } else { '' }
            Show-Info "测试成功：网络已自动拨回，账号密码有效。`n`n以后每次开机都会自动拨号，无需手动操作。$guard"
        }
        else {
            Show-Err "测试失败：拨号未能在 24 秒内恢复。`n`n常见原因：账号或密码错误、网线未插好。`n详细记录见脚本目录下的 dial.log，可重新运行本安装程序再试。"
        }
    }
    else {
        $guard = if ($Reconnect) { "`n`n掉线自动重连已启用：断线后 $reconnectSeconds 秒内自动恢复。" } else { '' }
        Show-Info "安装完成！`n`n以后每次开机将自动拨号（约 5 秒联网）。$guard`n`n日常管理（双击对应文件即可）：`n· 暂停/恢复自动拨号 → 暂停恢复.cmd`n· 完全卸载 → 卸载.cmd`n· 查看运行日志 → dial.log"
    }
}
catch {
    if ($Unattended) { Write-Host "ERROR: $($_.Exception.Message)"; exit 1 }
    Show-Err "安装失败：`n$($_.Exception.Message)"
    exit 1
}
